

# Numeric Types (সংখ্যা)

# int 
a = 10
print(type(a))

#float 
b = 3.123
print(type(b))

# complex
c = 3 + 4j
print(type(c))

# string
name = "Shazidul islam"

print(type(name))

# Boolean 
is_studen = True
is_married = False

print(is_studen)
print(type(is_married))

#list 
fruits = ["apple" , "banana" , "mango"]
print(type(fruits))

#dict

obj = {"a":1 , "b":"soon"}
print(obj)
print(type(obj))

# set {1 , 2 , 3}

num_onj = {10 , 2 , 3 , "number" , 4.6}
print(num_onj)
print(type(num_onj))

# None
nothing = None

print(type(nothing))

